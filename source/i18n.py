LANG = SETTINGS.value("lang", "ru")


def t(key: str) -> str:
    return I18N.get(LANG, I18N["ru"]).get(key, key)


def set_lang(lang: str) -> None:
    global LANG
    if lang in ("ru", "en"):
        LANG = lang
        SETTINGS.setValue("lang", lang)


def toggle_lang() -> str:
    new = "en" if LANG == "ru" else "ru"
    set_lang(new)
    return new